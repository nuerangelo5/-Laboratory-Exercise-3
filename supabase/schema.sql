-- 1. TABLE: equipment
-- Stores all college ICT and laboratory equipment records
CREATE TABLE IF NOT EXISTS public.equipment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_name TEXT NOT NULL CHECK (char_length(trim(equipment_name)) > 0), -- BR-01
  category TEXT NOT NULL,
  asset_code TEXT UNIQUE NOT NULL CHECK (char_length(trim(asset_code)) > 0), -- BR-02
  condition TEXT NOT NULL DEFAULT 'Good' CHECK (condition IN ('Good', 'Fair', 'For Repair')),
  availability TEXT NOT NULL DEFAULT 'Available' CHECK (availability IN ('Available', 'Borrowed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. TABLE: borrow_transactions
-- Stores borrowing and return logs referencing public.equipment(id) (1:M relationship)
CREATE TABLE IF NOT EXISTS public.borrow_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id BIGINT NOT NULL REFERENCES public.equipment(id) ON DELETE CASCADE,
  borrower_name TEXT NOT NULL CHECK (char_length(trim(borrower_name)) > 0), -- BR-04
  borrower_type TEXT NOT NULL CHECK (borrower_type IN ('Student', 'Faculty', 'Staff')),
  department TEXT NOT NULL CHECK (char_length(trim(department)) > 0),
  date_borrowed DATE NOT NULL DEFAULT CURRENT_DATE,
  due_date DATE NOT NULL,
  date_returned DATE,
  status TEXT NOT NULL DEFAULT 'Borrowed' CHECK (status IN ('Borrowed', 'Returned', 'Overdue')), -- BR-06
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_due_date_after_borrowed CHECK (due_date >= date_borrowed) -- BR-05
);

-- 3. INDEXES FOR FAST SEARCH, FILTERING & BORROWING HISTORY LOOKUPS
CREATE INDEX IF NOT EXISTS idx_equipment_asset_code ON public.equipment (asset_code);
CREATE INDEX IF NOT EXISTS idx_equipment_availability ON public.equipment (availability);
CREATE INDEX IF NOT EXISTS idx_borrow_transactions_equipment_id ON public.borrow_transactions (equipment_id);
CREATE INDEX IF NOT EXISTS idx_borrow_transactions_status ON public.borrow_transactions (status);
CREATE INDEX IF NOT EXISTS idx_borrow_transactions_due_date ON public.borrow_transactions (due_date);

-- 4. PRIVILEGES & ROW LEVEL SECURITY (RLS) - BR-11: Only authenticated users may manage records
GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.equipment TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.borrow_transactions TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

ALTER TABLE public.equipment ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.borrow_transactions ENABLE ROW LEVEL SECURITY;

